public class LogicalOperators {
    public static void main(String[] args) {

        boolean a = true;
        boolean b = false;

        // Logical AND
        System.out.println("a && b = " + (a && b));

        // Logical OR
        System.out.println("a || b = " + (a || b));

        // Logical NOT
        System.out.println("!a = " + (!a));
        System.out.println("!b = " + (!b));
    }
}