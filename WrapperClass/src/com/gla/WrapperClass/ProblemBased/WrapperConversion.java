package com.gla.WrapperClass.ProblemBased;

public class WrapperConversion {
    public static void main(String[] args) {
        Integer a = 100;
        Integer b = 200;
        Integer c = 300;
        Integer d = 400;

        System.out.println(a == b);
        System.out.println(c == d);
        System.out.println(a.equals(b));
    }
}
